"""Project export bundle (ZIP): document, BOM, wiring SVG, meshes, firmware, guide."""

from __future__ import annotations

import io
import json
import zipfile

from hwbp import mesh as M
from hwbp.cad import ParametricGenerator, export_assembly
from hwbp.layout import render_svg
from hwbp.mech import solve_layout
from hwbp.models import ProjectContent
from hwbp.pricing import build_bom


def guide_markdown(content: ProjectContent) -> str:
    out = [f"# {content.project_name}", "", content.project_description or "", ""]
    if content.instruction_preamble:
        out += ["## Tools", *[f"- {t}" for t in content.instruction_preamble.tools], "", "## Assumptions"]
        out += [f"- {a}" for a in content.instruction_preamble.assumptions] + [""]
    for i, step in enumerate(content.instruction_steps, 1):
        out.append(f"## {i}. {step.title or step.id}")
        for j, sub in enumerate(step.sub_steps, 1):
            out.append(f"### {i}.{j} {sub.title}")
            if sub.part_ids:
                out.append("Parts: " + ", ".join(sub.part_ids))
            out += [f"- {d}" for d in sub.details or []]
            out.append("")
    if content.issues:
        out += [
            "## Design review",
            *[f"- **{x.severity}** {x.code}: {x.message}" + (f" — {x.fix}" if x.fix else "") for x in content.issues],
        ]
    return "\n".join(out) + "\n"


def wiring_svg(content: ProjectContent, dark: bool = False) -> str:
    lay = content.wiring_layout or {}
    if not lay.get("nodes"):
        return '<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"/>'
    return render_svg(lay, lay.get("nodeMeta", {}), dark=dark)


def export_zip(content: ProjectContent, build_qty: int = 1, include_meshes: bool = True) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("project.json", json.dumps(content.dump(), indent=2))
        z.writestr("bom.csv", build_bom(content.nodes, build_qty).to_csv())
        z.writestr("wiring.svg", wiring_svg(content))
        z.writestr("guide.md", guide_markdown(content))
        z.writestr("viewer.html", render_viewer(content, with_meshes=include_meshes))
        for path, text in (content.firmware or {}).items():
            z.writestr(f"firmware/{path}", text)
        if include_meshes:
            layout = content.mech_layout or solve_layout(content)
            for name, data in export_assembly(content, layout).items():
                z.writestr(f"cad/{name}", data)
            gen = ParametricGenerator(content)
            for nid in layout.get("parts", {}):
                node = content.node(nid)
                if node is not None and node.type in ("3d_printed", "enclosure", "structural", "mechanism"):
                    z.writestr(f"cad/parts/{nid}.stl", M.to_stl_binary(gen.generate(node, None, {})))
        z.writestr(
            "README.md",
            f"# {content.project_name}\n\nGenerated by hwbp {content.engine_version or ''}.\n\n"
            "- project.json — full design document\n- bom.csv — bill of materials\n- wiring.svg — wiring diagram\n"
            "- guide.md — build guide\n- viewer.html — open in a browser (Info/Parts/Wiring/Mech/Instructions/Code)\n- firmware/ — PlatformIO project\n- cad/ — assembly (GLB/OBJ) and printable parts (STL)\n",
        )
    return buf.getvalue()


def render_viewer(content: ProjectContent, with_meshes: bool = True) -> str:
    """Self-contained viewer HTML with the project (and part meshes) embedded."""
    from importlib.resources import files

    from hwbp.cad import part_mesh_json

    tpl = files("hwbp").joinpath("viewer/index.html").read_text(encoding="utf-8")
    doc = json.dumps(content.dump()).replace("</", "<\\/")
    meshes = "null"
    if with_meshes and content.mech_layout:
        meshes = json.dumps(part_mesh_json(content, content.mech_layout)).replace("</", "<\\/")
    return tpl.replace("/*__PROJECT__*/null", doc, 1).replace("/*__MESHES__*/null", meshes, 1)
